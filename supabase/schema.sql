-- Quiz World: full database schema.
--
-- Run in the Supabase SQL Editor (or as a migration). Safe to re-run. It
-- creates everything the app reads and writes:
--   questions     the question bank
--   profiles      one row per user: role (user/admin) and assigned class
--   quiz_results  every finished quiz
-- plus row-level security, the sign-up trigger and the random-question RPC.
--
-- To make someone an admin, run (as the project owner, e.g. in the SQL Editor):
--   update public.profiles set role = 'admin' where email = 'person@example.com';

-- ── 0. Replace the early prototype `questions` table ─────────────────────
-- The first prototype used `question` + `options` columns. If that table is
-- still here, drop it, but only when it's empty, so no data can be lost.
do $$
begin
  if to_regclass('public.questions') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'questions' and column_name = 'question_text'
     )
  then
    if exists (select 1 from public.questions) then
      raise exception 'public.questions uses the old prototype layout and has rows. Migrate them before running this script.';
    end if;

    drop function if exists public.get_random_questions(integer, text, text, integer);
    drop function if exists public.get_random_questions(text, integer, integer, text);
    drop function if exists public.get_random_questions(text, text, text, integer);
    drop table public.questions;
  end if;
end;
$$;

-- ── 1. Tables ─────────────────────────────────────────────────────────────
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  role        text not null default 'user' check (role in ('user', 'admin')),
  class_level text,
  created_at  timestamptz not null default now()
);

create index if not exists profiles_email_idx on public.profiles (lower(email));

-- class_level is text so it can hold exam categories like "BCS 45" as well
-- as class numbers like "9".
create table if not exists public.questions (
  id             bigint generated by default as identity primary key,
  class_level    text not null default '6',
  subject        text not null default 'General',
  chapter        text not null default 'General',
  question_text  text not null,
  option_a       text not null,
  option_b       text not null,
  option_c       text not null,
  option_d       text not null,
  correct_answer text not null check (correct_answer in ('A', 'B', 'C', 'D')),
  explanation    text not null default '',
  created_by     uuid default auth.uid() references auth.users (id) on delete set null,
  created_at     timestamptz not null default now()
);

create index if not exists questions_filter_idx on public.questions (class_level, subject, chapter);

create table if not exists public.quiz_results (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null default auth.uid() references auth.users (id) on delete cascade,
  class_level      text,
  subject          text,
  question_limit   integer,
  duration_minutes integer,
  total_questions  integer not null default 0,
  correct_answers  integer not null default 0,
  wrong_answers    integer not null default 0,
  skipped_answers  integer not null default 0,
  score            integer not null default 0,
  percentage       numeric(5, 2) not null default 0,
  answers          jsonb,
  created_at       timestamptz not null default now()
);

create index if not exists quiz_results_user_idx on public.quiz_results (user_id, created_at desc);

-- ── 2. Helpers ────────────────────────────────────────────────────────────
-- SECURITY DEFINER so policies can check the caller's role without the
-- profiles policies recursing into themselves. Only reads the caller's row.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and role = 'admin'
  );
$$;

-- Same rules as normalizeClassLevel() in src/lib/normalizeClassLevel.js:
--   "BCS 45" / "BCS-45" / "45 BCS" -> "BCS 45", "Class 9" -> "9".
create or replace function public.normalize_class_level(p_value text)
returns text
language sql
immutable
set search_path = public
as $$
  select coalesce(
    'BCS ' || coalesce(
      (regexp_match(trim(p_value), '^bcs[-\s]*(\d+)', 'i'))[1],
      (regexp_match(trim(p_value), '^(\d+)[-\s]*bcs', 'i'))[1]
    ),
    (regexp_match(trim(p_value), '^class\s+(\d+)$', 'i'))[1],
    trim(coalesce(p_value, ''))
  );
$$;

-- ── 3. Profiles: created at sign-up, role and class protected ─────────────
-- A profile row is created for every new auth user, using the class picked
-- on the sign-up form (sent as user metadata).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role, class_level)
  values (
    new.id,
    new.email,
    'user',
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'class_level', new.raw_user_meta_data ->> 'classLevel', '')), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Signed-in users who aren't admins can't make themselves admin or move
-- themselves to another class. Admins, and the project owner in the SQL
-- Editor (no signed-in user), can change anything.
create or replace function public.protect_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    if tg_op = 'INSERT' then
      new.role := 'user';
    else
      new.role := old.role;
      new.class_level := old.class_level;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_fields on public.profiles;
create trigger protect_profile_fields
  before insert or update on public.profiles
  for each row execute function public.protect_profile_fields();

-- ── 4. Row-level security ─────────────────────────────────────────────────
alter table public.profiles enable row level security;
alter table public.questions enable row level security;
alter table public.quiz_results enable row level security;

-- profiles
drop policy if exists "Read own profile or any if admin" on public.profiles;
create policy "Read own profile or any if admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "Create own profile" on public.profiles;
create policy "Create own profile" on public.profiles
  for insert to authenticated
  with check (id = auth.uid());

drop policy if exists "Update own profile or any if admin" on public.profiles;
create policy "Update own profile or any if admin" on public.profiles
  for update to authenticated
  using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());

drop policy if exists "Admins delete profiles" on public.profiles;
create policy "Admins delete profiles" on public.profiles
  for delete to authenticated
  using (public.is_admin());

-- questions
drop policy if exists "Signed-in users read questions" on public.questions;
create policy "Signed-in users read questions" on public.questions
  for select to authenticated
  using (true);

drop policy if exists "Admins add questions" on public.questions;
create policy "Admins add questions" on public.questions
  for insert to authenticated
  with check (public.is_admin());

drop policy if exists "Admins edit questions" on public.questions;
create policy "Admins edit questions" on public.questions
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins delete questions" on public.questions;
create policy "Admins delete questions" on public.questions
  for delete to authenticated
  using (public.is_admin());

-- quiz_results
drop policy if exists "Read own results or any if admin" on public.quiz_results;
create policy "Read own results or any if admin" on public.quiz_results
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists "Save own results" on public.quiz_results;
create policy "Save own results" on public.quiz_results
  for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists "Admins delete results" on public.quiz_results;
create policy "Admins delete results" on public.quiz_results
  for delete to authenticated
  using (public.is_admin());

-- ── 5. Random questions RPC ───────────────────────────────────────────────
-- Remove older integer versions: PostgREST can't choose between two
-- functions with the same argument names.
drop function if exists public.get_random_questions(integer, text, text, integer);
drop function if exists public.get_random_questions(text, integer, integer, text);

-- Same grouping as isClassInGroup() in src/lib/normalizeClassLevel.js.
-- SECURITY INVOKER: runs with the caller's permissions, so the policies
-- above still apply.
create or replace function public.get_random_questions(
  p_class_level text,
  p_subject text,
  p_chapter text,
  p_limit integer
)
returns setof public.questions
language sql
stable
security invoker
set search_path = public
as $$
  select q.*
  from public.questions q
  where (
    case
      when public.normalize_class_level(p_class_level) ~* '^bcs$'
        then public.normalize_class_level(q.class_level) ~* '^bcs\s*\d+'
      when public.normalize_class_level(p_class_level) in ('9', '10')
        then public.normalize_class_level(q.class_level) in ('9', '10')
      when public.normalize_class_level(p_class_level) in ('11', '12')
        then public.normalize_class_level(q.class_level) in ('11', '12')
      else lower(public.normalize_class_level(q.class_level)) = lower(public.normalize_class_level(p_class_level))
    end
  )
    and (p_subject is null or p_subject = 'All Subjects' or q.subject = p_subject)
    and (p_chapter is null or p_chapter = 'All Chapters' or q.chapter = p_chapter)
  order by random()
  limit greatest(coalesce(p_limit, 1), 1);
$$;

-- ── 6. Permissions ────────────────────────────────────────────────────────
-- Logged-out visitors (anon) get nothing. Postgres lets PUBLIC execute new
-- functions by default and Supabase grants anon, so revoke both.
revoke all on public.profiles, public.questions, public.quiz_results from anon;
grant select, insert, update, delete on public.profiles, public.questions, public.quiz_results to authenticated;

revoke execute on function public.is_admin() from public, anon;
revoke execute on function public.normalize_class_level(text) from public, anon;
revoke execute on function public.get_random_questions(text, text, text, integer) from public, anon;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.protect_profile_fields() from public, anon, authenticated;

grant execute on function public.is_admin() to authenticated;
grant execute on function public.normalize_class_level(text) to authenticated;
grant execute on function public.get_random_questions(text, text, text, integer) to authenticated;
